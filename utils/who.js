// 百分位对应 z 值
const Z = { p3: -1.88, p15: -1.04, p50: 0, p85: 1.04, p97: 1.88 }

// 返回每个月龄的 P3/P15/P50/P85/P97 近似值
function whoBand(gender, type) {
  const src = ((WHO[gender] && WHO[gender][type]) || WHO.boy[type])
  return Object.keys(src.M).map(m => {
    const M = src.M[m]
    const S = src.S[m]
    const month = Number(m)
    return {
      month,
      p3: +(M + Z.p3 * S).toFixed(1),
      p15: +(M + Z.p15 * S).toFixed(1),
      p50: +M.toFixed(1),
      p85: +(M + Z.p85 * S).toFixed(1),
      p97: +(M + Z.p97 * S).toFixed(1)
    }
  }).sort((a, b) => a.month - b.month)
}

// 兼容旧调用：仅返回中位数
function whoPoints(gender, type) {
  return whoBand(gender, type).map(p => ({ month: p.month, val: p.p50 }))
}

module.exports = { whoBand, whoPoints }
