// 百分位对应的 z 分位值
const Z = { p3: -1.88079, p15: -1.03643, p50: 0, p85: 1.03643, p97: 1.88079 }
const MAX_MONTH = 60

function lmsAt(gender, type, month) {
  const src = ((WHO_LMS[gender] && WHO_LMS[gender][type]) || WHO_LMS.boy[type])
    .slice().sort((a, b) => a[0] - b[0])
  if (month <= src[0][0]) return { L: src[0][1], M: src[0][2], S: src[0][3] }
  const last = src[src.length - 1]
  if (month >= last[0]) return { L: last[1], M: last[2], S: last[3] }
  for (let i = 1; i < src.length; i++) {
    if (month <= src[i][0]) {
      const a = src[i - 1], b = src[i]
      const t = (month - a[0]) / (b[0] - a[0])
      return {
        L: a[1] + (b[1] - a[1]) * t,
        M: a[2] + (b[2] - a[2]) * t,
        S: a[3] + (b[3] - a[3]) * t
      }
    }
  }
  return { L: last[1], M: last[2], S: last[3] }
}

function lmsValue(L, M, S, z) {
  if (Math.abs(L) < 1e-7) return M * Math.exp(S * z)
  return M * Math.pow(1 + L * S * z, 1 / L)
}

// 返回 0..MAX_MONTH 每个月龄的 P3/P15/P50/P85/P97（基于官方 LMS + z 公式）
function whoBand(gender, type) {
  const arr = []
  for (let m = 0; m <= MAX_MONTH; m++) {
    const { L, M, S } = lmsAt(gender, type, m)
    arr.push({
      month: m,
      p3: +lmsValue(L, M, S, Z.p3).toFixed(1),
      p15: +lmsValue(L, M, S, Z.p15).toFixed(1),
      p50: +lmsValue(L, M, S, Z.p50).toFixed(1),
      p85: +lmsValue(L, M, S, Z.p85).toFixed(1),
      p97: +lmsValue(L, M, S, Z.p97).toFixed(1)
    })
  }
  return arr
}

// 兼容旧调用：仅返回中位数
function whoPoints(gender, type) {
  return whoBand(gender, type).map(p => ({ month: p.month, val: p.p50 }))
}

module.exports = { whoBand, whoPoints, MAX_MONTH }
